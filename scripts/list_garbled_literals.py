from pathlib import Path
import re

FILES = [
    "lib/app.dart",
    "lib/core/services/call_service.dart",
    "lib/features/chat/providers/message_provider.dart",
    "backend/internal/handlers/call_handler.go",
    "backend/internal/handlers/meeting_handler.go",
]

SUSPICIOUS = set(
    map(
        chr,
        [
            0x95C2, 0x93C6, 0x5987, 0x7459, 0x9352, 0x9422, 0x7F02, 0x93B4,
            0x986B, 0x95B2, 0x9359, 0x5A11, 0x7487, 0x93BA, 0x6B06, 0x6B39,
            0x5815, 0x7029, 0x7B1B, 0xFF0C, 0x9286, 0x3006, 0x9225, 0x9471,
            0x7EFE, 0x935A, 0x9423, 0x6F7C, 0x95AB, 0x93C1, 0x9417, 0x9427,
            0x704F, 0x9483, 0x7B17, 0x941D, 0x6FA7, 0x9350, 0x9855, 0x68EB,
            0x6D32, 0x713D, 0x7023, 0x934E, 0x6A00, 0x9366, 0x9411, 0x6FEE,
            0x708A, 0x95B2, 0x95B8, 0x95B9, 0x95BA, 0x95BB, 0x95BC, 0x95BD,
            0x95BE, 0x95BF, 0x941A, 0x9429, 0x942B, 0x942D, 0x942E, 0x942F,
            0x9430, 0x9431, 0x9432, 0x9433, 0x9434, 0x9435, 0x9436, 0x9437,
            0x9438, 0x9439, 0x943A, 0x943B, 0x943C, 0x943D, 0x943E, 0x943F,
            0x93B4, 0x93B5, 0x93B6, 0x93B7, 0x93B8, 0x93B9, 0x93BA, 0x93BB,
            0x93BC, 0x93BD, 0x93BE, 0x93BF,
        ],
    )
)

string_re = re.compile(r"""(['"])(.*?)(?<!\\)\1""")

out = []
for file in FILES:
    path = Path(file)
    out.append(f"## {file}")
    text = path.read_text(encoding="utf-8")
    for lineno, line in enumerate(text.splitlines(), start=1):
        for m in string_re.finditer(line):
            s = m.group(2)
            if any(ch in SUSPICIOUS for ch in s):
                out.append(f"{lineno}: {s}")
    out.append("")

Path("docs/garbled_literals.txt").write_text("\n".join(out), encoding="utf-8")
print("written docs/garbled_literals.txt")
